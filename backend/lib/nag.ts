import { Token, Validations, type CfnElement, type Stack } from 'aws-cdk-lib';
import type { IConstruct } from 'constructs';

const NS = 'AwsSolutions::';

/** Resources whose CDK-generated wildcard permissions are acknowledged by logical id. */
export interface NagRefs {
  table: IConstruct;
  buckets: IConstruct[];
  /** Lambda functions invoked by Step Functions (LambdaInvoke grants `<fn>:*` for versions). */
  invokedFunctions: IConstruct[];
  stateMachines: IConstruct[];
}

/**
 * Reviewed cdk-nag (AwsSolutions) findings that are acceptable for a
 * small internal dashboard (a handful of invited accounts). Each entry states why.
 */
export function applyNagSuppressions(stack: Stack, refs: NagRefs): void {
  const rules: Record<string, string> = {
    'AwsSolutions-IAM4[Policy::arn:<AWS::Partition>:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole]':
      'AWS-managed least-privilege policy for Lambda logging.',
    'AwsSolutions-IAM4[Policy::arn:<AWS::Partition>:iam::aws:policy/service-role/AmazonAPIGatewayPushToCloudWatchLogs]':
      'AWS-managed policy required for API Gateway access logging.',
    'AwsSolutions-IAM5[Resource::*]':
      'X-Ray tracing and CloudWatch Logs delivery for Step Functions require "*" (AWS service limitation).',
    'AwsSolutions-L1': 'Functions use Node.js 24; CDK-internal singleton functions (bucket deployment, auto-delete) are managed by CDK.',
    'AwsSolutions-COG2': 'MFA is OPTIONAL with TOTP enabled; switch to REQUIRED if company policy demands it.',
    'AwsSolutions-COG3': 'Threat protection (Plus tier) is not needed for a handful of invited users.',
    'AwsSolutions-COG8': 'Plus feature plan (threat protection) is not needed for a handful of invited users.',
    'AwsSolutions-APIG2': 'Request bodies and parameters are validated in Lambda with zod schemas.',
    'AwsSolutions-APIG3': 'WAF is optional for an internal dashboard behind Cognito; add a web ACL if required.',
    'AwsSolutions-APIG4': 'All routes use the Cognito authorizer; only CORS preflight (OPTIONS) mock methods are unauthenticated.',
    'AwsSolutions-COG4': 'All routes use the Cognito authorizer; only CORS preflight (OPTIONS) mock methods are unauthenticated.',
    'AwsSolutions-APIG6': 'Access logging is enabled at the stage; execution logging is left off to avoid logging request bodies.',
    'AwsSolutions-CFR1': 'No geo restriction: users may travel.',
    'AwsSolutions-CFR2': 'WAF is optional for a static SPA whose API is protected by Cognito.',
    'AwsSolutions-CFR3': 'CloudFront access logs are not needed for a small internal dashboard.',
    'AwsSolutions-CFR4': 'The default CloudFront certificate is used until a custom domain is configured.',
    'AwsSolutions-S1': 'Server access logs are not needed for private app buckets accessed only by CloudFront and Lambda.',
    'AwsSolutions-SF1': 'State machines log errors to CloudWatch; full event logging would include article data.',
  };

  // Wildcards produced by CDK grant helpers, scoped to this stack's resources.
  const grantReason = 'Generated by CDK grant helpers and scoped to resources in this stack.';
  for (const action of ['s3:List*', 's3:GetObject*', 's3:GetBucket*', 's3:DeleteObject*', 's3:Abort*']) {
    rules[`AwsSolutions-IAM5[Action::${action}]`] = grantReason;
  }
  const logicalId = (c: IConstruct) => stack.getLogicalId(c.node.defaultChild as CfnElement);
  rules[`AwsSolutions-IAM5[Resource::<${logicalId(refs.table)}.Arn>/index/*]`] = grantReason;
  for (const bucket of refs.buckets) {
    rules[`AwsSolutions-IAM5[Resource::<${logicalId(bucket)}.Arn>/*]`] = grantReason;
    rules[`AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:s3:::<${logicalId(bucket)}>/*]`] = grantReason;
    // The News API deletes only the accounts' extracted article texts (users/*) when news is deleted.
    rules[`AwsSolutions-IAM5[Resource::<${logicalId(bucket)}.Arn>/users/*]`] = grantReason;
  }
  for (const fn of refs.invokedFunctions) {
    rules[`AwsSolutions-IAM5[Resource::<${logicalId(fn)}.Arn>:*]`] =
      'Step Functions LambdaInvoke grants all versions/aliases of the task function.';
  }

  // Values that embed the account/region (literal when the CLI resolved an account).
  const account = Token.isUnresolved(stack.account) ? '<AWS::AccountId>' : stack.account;
  const region = Token.isUnresolved(stack.region) ? '<AWS::Region>' : stack.region;
  const partition = Token.isUnresolved(stack.region) ? '<AWS::Partition>' : 'aws';
  rules[`AwsSolutions-IAM5[Resource::arn:${partition}:s3:::cdk-hnb659fds-assets-${account}-${region}/*]`] =
    'CDK bucket deployment reads the CDK bootstrap asset bucket.';
  for (const machine of refs.stateMachines) {
    const name = `{"Fn::Select":[6,{"Fn::Split":[":",{"Ref":"${logicalId(machine)}"}]}]}`;
    const reason = 'Distributed Map child executions of this state machine.';
    rules[`AwsSolutions-IAM5[Resource::arn:${partition}:states:${region}:${account}:execution:${name}:*]`] = reason;
    rules[`AwsSolutions-IAM5[Resource::arn:${partition}:states:${region}:${account}:execution:${name}/*:*]`] = reason;
  }

  for (const [id, reason] of Object.entries(rules)) {
    Validations.of(stack).acknowledge({ id: `${NS}${id}`, reason });
  }
}
